const esc=s=>String(s).replace(/[&<>"]/g,c=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;'})[c]);

export function renderUpdateNotes(notes=UPDATE_NOTES) {
 return notes.map((n,i)=>`<section class="un-section"><p class="un-date">${esc(n.date)}</p>`+
  `<h3><span class="un-no">${i+1}.</span> ${esc(n.title)}</h3>`+
  n.items.map(([h,b])=>`<div class="un-item"><h4>${esc(h)}</h4><p>${esc(b)}</p></div>`).join('')+`</section>`).join('');
}
